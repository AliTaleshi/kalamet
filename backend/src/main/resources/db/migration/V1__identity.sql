CREATE TABLE addresses (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    recipient_name   VARCHAR(200) NOT NULL,
    recipient_mobile VARCHAR(11)  NOT NULL,
    province_id      SMALLINT     NOT NULL,
    city             VARCHAR(100) NOT NULL,
    address_line     TEXT         NOT NULL,       -- street, alley, building (نشانی پستی)
    plaque           VARCHAR(20)  NOT NULL,       -- پلاک
    unit             VARCHAR(20),                 -- واحد
    postal_code      VARCHAR(10)  NOT NULL,
    is_default       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_addresses_user        FOREIGN KEY (user_id)     REFERENCES users (id)     ON DELETE CASCADE,
    CONSTRAINT fk_addresses_province    FOREIGN KEY (province_id) REFERENCES provinces (id) ON DELETE RESTRICT,
    CONSTRAINT ck_addresses_mobile      CHECK (recipient_mobile ~ '^09[0-9]{9}$'),
    CONSTRAINT ck_addresses_postal_code CHECK (postal_code ~ '^[0-9]{10}$')
);

CREATE INDEX idx_addresses_user ON addresses (user_id);

-- At most one default address per user, enforced by the database.
CREATE UNIQUE INDEX uk_addresses_one_default ON addresses (user_id) WHERE is_default;
