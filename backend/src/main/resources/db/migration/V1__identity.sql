-- Layer 1: Identity
-- Customers sign in with their mobile number and a one-time SMS code, so there
-- are no passwords. A user row is created on the first successful code check.

CREATE TABLE users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mobile     VARCHAR(11)  NOT NULL,            -- 09xxxxxxxxx
    email      VARCHAR(255),
    first_name VARCHAR(100),                     -- filled in after the first login
    last_name  VARCHAR(100),
    role       VARCHAR(20)  NOT NULL DEFAULT 'CUSTOMER',
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_users_mobile      UNIQUE (mobile),
    CONSTRAINT uk_users_email       UNIQUE (email),
    CONSTRAINT ck_users_mobile      CHECK (mobile ~ '^09[0-9]{9}$'),
    CONSTRAINT ck_users_email_lower CHECK (email = lower(email)),
    CONSTRAINT ck_users_role        CHECK (role IN ('CUSTOMER', 'ADMIN'))
);

-- One-time login codes. Not linked to users: the number may not have an account yet.
-- Only a SHA-256 hash of the code is stored.
CREATE TABLE otp_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mobile      VARCHAR(11) NOT NULL,
    code_hash   VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    attempts    INTEGER     NOT NULL DEFAULT 0,  -- wrong guesses so far
    consumed_at TIMESTAMPTZ,                     -- set once the code is used
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_otp_mobile   CHECK (mobile ~ '^09[0-9]{9}$'),
    CONSTRAINT ck_otp_attempts CHECK (attempts >= 0)
);

-- Latest code per number, and rate limiting ("max N codes per 10 minutes").
CREATE INDEX idx_otp_mobile_created ON otp_codes (mobile, created_at DESC);

-- Reference data: Iran's 31 provinces.
CREATE TABLE provinces (
    id   SMALLINT    PRIMARY KEY,
    name VARCHAR(50) NOT NULL,

    CONSTRAINT uk_provinces_name UNIQUE (name)
);

